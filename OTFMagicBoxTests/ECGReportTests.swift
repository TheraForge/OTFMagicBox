    @Test("Secure attachment is persisted by occurrence without binary outcome data")
    func secureAttachmentIsPersistedByOccurrence() async throws {
        let report = try #require(makeReport())
        let attachment = try #require(makeAttachment(for: report))
        let attachmentStore = FakeECGReportAttachmentStore(uploadResult: .success(attachment))
        let task = makeTask(id: "secure-ecg-outcome", start: date, end: nil)
        let event = try #require(SensorTaskOutcomeHelper.event(for: task, on: date))
        let careKitStore = OCKStore(
            name: "SecureECGOutcomeTests-\(UUID().uuidString)",
            type: .inMemory
        )
        try await add(task: task, to: careKitStore)

        let success = await send(
            SensorOutcomePayload(
                metric: .ecg,
                reading: makeReading(),
                mode: .sensor,
                ecgReport: report
            ),
            task: task,
            occurrence: event.occurrence,
            store: careKitStore,
            attachmentStore: attachmentStore
        )
        let outcomes = try await fetchOutcomes(from: careKitStore, on: date)
        let outcome = try #require(outcomes.first)

        #expect(success)
        #expect(attachmentStore.uploadedReports == [report])
        #expect(attachmentStore.committedAttachments.count == 1)
        #expect(attachmentStore.committedAttachments.first?.attachmentID == attachment.attachmentID)
        #expect(attachmentStore.committedAttachments.first?.ownerID == task.uuid.uuidString)
        #expect(outcome.taskOccurrenceIndex == event.occurrence)
        #expect(!outcome.values.contains { $0.type == .binary })
        guard case .payload(let persistedPayload) = SensorOutcomeCodec.decode(
            metric: .ecg,
            values: outcome.values
        ) else {
            Issue.record("Expected a named ECG outcome")
            return
        }
        #expect(persistedPayload.ecgReport == nil)
        #expect(persistedPayload.ecgReportAttachment == attachment)
    }

