    @Test("Attachment store uploads ciphertext and decrypts downloaded reports")
    func attachmentStoreRoundTripsEncryptedReport() async throws {
        let report = try #require(makeReport())
        let attachmentID = "ecg-attachment-1"
        let storageKey = Array(repeating: UInt8(0x24), count: 32)
        var storedData = Data()
        var storedEncryptedKey = ""
        var storedHash = ""
        var storedFileName = ""
        var uploadedLocation: Request.AttachmentLocation?
        let isolatedDefaults = makeIsolatedUserDefaults(prefix: "ecg-attachment-store")
        defer { isolatedDefaults.cleanup() }
        let registry = ECGReportAttachmentRegistry(
            defaults: isolatedDefaults.defaults,
            namespace: { "test-user" }
        )

        let store = ECGReportAttachmentStore(
            storageKey: { storageKey },
            uploadRequest: { data, fileName, location, encryptedKey, hash in
                storedData = data
                storedEncryptedKey = encryptedKey
                storedHash = hash
                storedFileName = fileName
                uploadedLocation = location
                return Just(Response.FileResponse(
                    metadata: makeMetadata(
                        attachmentID: attachmentID,
                        fileName: fileName,
                        encryptedFileKey: encryptedKey,
                        hashFileKey: hash
                    ),
                    data: data
                ))
                .setFailureType(to: ForgeError.self)
                .eraseToAnyPublisher()
            },
            downloadRequest: { requestedID, location in
                #expect(requestedID == attachmentID)
                #expect(location == .documents)
                return Just(Response.FileResponse(
                    metadata: makeMetadata(
                        attachmentID: attachmentID,
                        fileName: storedFileName,
                        encryptedFileKey: storedEncryptedKey,
                        hashFileKey: storedHash
                    ),
                    data: storedData
                ))
                .setFailureType(to: ForgeError.self)
                .eraseToAnyPublisher()
            },
            deleteRequest: { _ in
                Just(Response.DeleteFile(error: false, message: "Deleted", statusCode: 200))
                    .setFailureType(to: ForgeError.self)
                    .eraseToAnyPublisher()
            },
            registry: registry
        )

        let attachment = try await upload(report, using: store).get()
        let downloaded = try await download(attachment, using: store).get()

        #expect(uploadedLocation == .documents)
        #expect(storedData != report.pdfData)
        #expect(attachment.attachmentID == attachmentID)
        #expect(downloaded == report)
        #expect(registry.pendingAttachmentIDs == [attachmentID])
    }

    @Test("Attachment download rejects substituted response metadata")
    func attachmentDownloadRejectsSubstitutedMetadata() async throws {
        let report = try #require(makeReport())
        let storageKey = Array(repeating: UInt8(0x24), count: 32)
        let envelope = try SecureAttachmentCryptor().encrypt(
            report.pdfData,
            storageKey: storageKey
        )
        let attachment = try #require(makeAttachment(
            for: report,
            encryptedFileKey: envelope.encryptedFileKey,
            hashFileKey: envelope.hashFileKey
        ))
        let cases = [
            makeMetadata(
                attachmentID: "different-attachment",
                fileName: attachment.fileName,
                encryptedFileKey: envelope.encryptedFileKey,
                hashFileKey: envelope.hashFileKey
            ),
            makeMetadata(
                attachmentID: attachment.attachmentID,
                fileName: "different.pdf",
                encryptedFileKey: envelope.encryptedFileKey,
                hashFileKey: envelope.hashFileKey
            ),
            makeMetadata(
                attachmentID: attachment.attachmentID,
                fileName: attachment.fileName,
                encryptedFileKey: envelope.encryptedFileKey,
                hashFileKey: envelope.hashFileKey,
                location: .profile
            ),
            makeMetadata(
                attachmentID: attachment.attachmentID,
                fileName: attachment.fileName,
                encryptedFileKey: envelope.encryptedFileKey + "00",
                hashFileKey: envelope.hashFileKey
            ),
            makeMetadata(
                attachmentID: attachment.attachmentID,
                fileName: attachment.fileName,
                encryptedFileKey: envelope.encryptedFileKey,
                hashFileKey: envelope.hashFileKey + "00"
            )
        ]

        for metadata in cases {
            let store = makeAttachmentStore(
                storageKey: storageKey,
                downloadResponse: Response.FileResponse(
                    metadata: metadata,
                    data: envelope.encryptedData
                )
            )

            switch await download(attachment, using: store) {
            case .success:
                Issue.record("Substituted attachment metadata was accepted")
            case .failure(let error):
                #expect(
                    error as? ECGReportAttachmentStoreError == .invalidAttachmentMetadata
                )
            }
        }
    }

