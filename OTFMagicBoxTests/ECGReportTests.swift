            Issue.record("Expected a named ECG payload")
            return
        }
        #expect(decodedPayload.ecgReport == nil)
        #expect(decodedPayload.ecgReportAttachment == attachment)
        #expect(!decodedOutcome.values.contains { $0.type == .binary })
    }

