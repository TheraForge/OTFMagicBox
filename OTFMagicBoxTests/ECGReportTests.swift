private func upload(
    _ report: ECGReport,
    using store: ECGReportAttachmentStoring
) async -> Result<ECGReportAttachment, Error> {
    await withCheckedContinuation { continuation in
        store.upload(report: report) { continuation.resume(returning: $0) }
    }
}

private func download(
    _ attachment: ECGReportAttachment,
    using store: ECGReportAttachmentStoring
) async -> Result<ECGReport, Error> {
    await withCheckedContinuation { continuation in
        store.download(attachment: attachment) { continuation.resume(returning: $0) }
    }
}

private func add(task: OCKTask, to store: OCKStore) async throws {
    let result = await withCheckedContinuation { continuation in
        store.addAnyTask(task, callbackQueue: .main) { continuation.resume(returning: $0) }
    }
    if case .failure(let error) = result {
        throw error
    }
}

private func fetchOutcomes(from store: OCKStore, on date: Date) async throws -> [OCKAnyOutcome] {
    let result = await withCheckedContinuation { continuation in
        store.fetchAnyOutcomes(
            query: OCKOutcomeQuery(for: date),
            callbackQueue: .main
        ) { continuation.resume(returning: $0) }
    }
    switch result {
    case .success(let outcomes):
        return outcomes
    case .failure(let error):
        throw error
    }
}
