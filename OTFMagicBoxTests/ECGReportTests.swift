                .eraseToAnyPublisher()
            }
        )

        let attachment = try await upload(report, using: store).get()
        let downloadedReport = try await download(attachment, using: store).get()

        #expect(attachment.fileName.isEmpty == false)
        #expect(downloadedReport == report)
    }
}

