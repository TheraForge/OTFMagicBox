            name: "AccountBoundSecureECGTests-\(UUID().uuidString)",
            type: .inMemory
        )
        try await add(task: task, to: initiatingStore)
        var activeSession = "patient-a"
        var syncCount = 0

        let success = await withCheckedContinuation { continuation in
            SensorTaskOutcomeHelper.sendOutcome(
                payload: SensorOutcomePayload(
                    metric: .ecg,
                    reading: .ecg(
                        classification: .sinusRhythm,
                        averageBPM: 82,
                        samplingHz: 512,
