    @Test("CareKit and JSON preserve the secure attachment reference")
    func careKitAndJSONPreserveAttachmentReference() throws {
        let report = try #require(makeReport())
        let attachment = try #require(makeAttachment(for: report))
        let payload = SensorOutcomePayload(
            metric: .ecg,
            reading: makeReading(),
            mode: .sensor,
            ecgReportAttachment: attachment
        )
        let outcome = OCKOutcome(
            taskUUID: UUID(),
            taskOccurrenceIndex: 2,
            values: SensorOutcomeCodec.encode(payload)
        )

        let data = try JSONEncoder().encode(outcome)
        let decodedOutcome = try JSONDecoder().decode(OCKOutcome.self, from: data)
        let decoded = SensorOutcomeCodec.decode(metric: .ecg, values: decodedOutcome.values)

        #expect(decodedOutcome.values == outcome.values)
        #expect(decoded == .payload(payload))
